/**
 * Generates TypeScript types from the card JSON Schemas.
 *   npm run gen:types                       (reads the store found by resolveDataDir)
 *   DATA_DIR=/path/to/DSTBG_DATA npm run gen:types
 * Output is committed, so CI and the Docker build never need the store.
 * Replaced by types generated from the API's /openapi.json once it exists.
 */
import { mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compile, type JSONSchema } from 'json-schema-to-typescript';
import { resolveDataDir } from './data-paths.ts';

const OUT_DIR = fileURLToPath(new URL('../src/shared/api/generated/', import.meta.url));
const BANNER = (file: string) =>
  `/* Generated by scripts/gen-types.ts from schema/${file}. Do not edit; run \`npm run gen:types\`. */`;

const CROSS_FIELD = ['oneOf', 'anyOf', 'allOf', 'not', 'if', 'then', 'else'] as const;

/**
 * Drops validation-only combinators the generator can't type usefully: cross-field rules on
 * objects (level xor boss, `sets` only when shared) and pattern/enum mixes on strings (setup
 * items). Value unions such as `range: number | "infinite"` have no `properties` and stay.
 */
function simplify(node: unknown): void {
  if (Array.isArray(node)) {
    node.forEach(simplify);
    return;
  }
  if (typeof node !== 'object' || node === null) return;
  const schema = node as Record<string, unknown>;
  if ('properties' in schema || schema.type === 'string') {
    for (const key of CROSS_FIELD) delete schema[key];
  }
  Object.values(schema).forEach(simplify);
}

const schemaDir = join(resolveDataDir(), 'schema');
const files = (await readdir(schemaDir)).filter((f) => f.endsWith('.schema.json')).sort();
if (files.length === 0) throw new Error(`gen-types: no *.schema.json in ${schemaDir}`);

await rm(OUT_DIR, { recursive: true, force: true });
await mkdir(OUT_DIR, { recursive: true });

const exports: string[] = [];
for (const file of files) {
  const type = file.replace('.schema.json', ''); // treasure, enemy, …
  const name = `Raw${type[0]?.toUpperCase() ?? ''}${type.slice(1)}`; // RawTreasure, …
  const schema = JSON.parse(await readFile(join(schemaDir, file), 'utf8')) as JSONSchema;
  // The title would name the type ("Treasure card"); the Raw* name says it isn't normalized yet.
  delete schema.title;
  delete schema.$id;
  simplify(schema);
  const ts = await compile(schema, name, {
    bannerComment: BANNER(file),
    additionalProperties: false,
    strictIndexSignatures: true,
    format: true,
  });
  await writeFile(join(OUT_DIR, `${type}.ts`), ts);
  exports.push(`export type { ${name} } from './${type}';`);
}

await writeFile(join(OUT_DIR, 'index.ts'), `${BANNER('*.schema.json')}\n${exports.join('\n')}\n`);
console.log(`gen-types: ${files.length} schemas from ${schemaDir} → src/shared/api/generated/`);
